#!/usr/bin/env node
/**
 * Generate `docs/atlas-tracker.json` from the Atlas's own §9 screen registry,
 * preserving any statuses already recorded.
 *
 * ⚠️ THE REGISTRY IS PARSED, NOT TRANSCRIBED. A hand-copied list of 270 screens
 * drifts from the spec the first time the spec changes, and then the tracker
 * quietly starts measuring against the wrong target. Re-running this picks up
 * Atlas edits; the `status` fields are merged forward so regenerating never
 * loses recorded progress.
 *
 * ⚠️ The Atlas says "256 screens" in ten places and "270" in eight. §9.10's
 * reconciliation table is machine-counted and says 270, and `OQ-538` explains
 * the difference (M-28 was added later). This script asserts 270 so a bad parse
 * fails loudly rather than producing a plausible-looking short list.
 *
 *   node scripts/build-atlas-tracker.mjs
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const ATLAS = path.join(root, 'MD FILES', 'UI_ATLAS.md')
const OUT = path.join(root, 'docs', 'atlas-tracker.json')

/** §9 spans these lines; the registry tables live inside it. */
const REGISTRY_FROM = 1800
const REGISTRY_TO = 2135
const EXPECTED = 270

/** The seven §10.4 axes, plus the overall status. */
const BLANK_AXES = {
  visible: 'NONE',
  navigation: 'NONE',
  demoData: 'NONE',
  responsive: 'NONE',
  accessibility: 'NONE',
  tests: 'NONE',
  aiUx: 'NONE',
}

function clean(s) {
  return s.replaceAll('**', '').replaceAll('`', '').trim()
}

const lines = (await readFile(ATLAS, 'utf8')).split('\n')
const screens = []

for (const line of lines.slice(REGISTRY_FROM, REGISTRY_TO)) {
  const m = /^\|\s*\*?\*?`(S-\d{2}-\d{2})`\*?\*?\s*\|(.+)$/.exec(line.trim())
  if (m === null) continue

  const cells = m[2]
    .split('|')
    .map((c) => c.trim())
    .filter((c) => c !== '')
  if (cells.length < 6) continue

  const [name, route, arc, personas, ai, tier] = cells.slice(0, 6).map(clean)
  screens.push({
    id: m[1],
    module: `M-${m[1].split('-')[1]}`,
    name,
    route,
    arc,
    personas: personas.split(',').map((p) => p.trim()).filter(Boolean),
    // `⊘` is the Atlas's "none" marker; it is not an AI id.
    ai: ai.split(',').map((a) => a.trim()).filter((a) => a !== '' && a !== '⊘'),
    tier,
    status: 'NOT_STARTED',
    ...BLANK_AXES,
    actualRoute: null,
    atlasDiscrepancy: null,
    notes: null,
  })
}

if (screens.length !== EXPECTED) {
  throw new Error(
    `Parsed ${screens.length} screens from the §9 registry, expected ${EXPECTED}. ` +
      'The registry line range or row format has changed — fix the parse rather than ' +
      'lowering EXPECTED, or the tracker will silently measure against a short list.',
  )
}

const ids = new Set(screens.map((s) => s.id))
if (ids.size !== screens.length) {
  throw new Error('Duplicate screen ids in the parsed registry.')
}

// Merge forward anything already recorded, so regenerating is lossless.
let previous = {}
if (existsSync(OUT)) {
  const prior = JSON.parse(await readFile(OUT, 'utf8'))
  for (const s of prior.screens ?? []) previous[s.id] = s
}

const KEEP = ['status', ...Object.keys(BLANK_AXES), 'actualRoute', 'atlasDiscrepancy', 'notes']
for (const s of screens) {
  const was = previous[s.id]
  if (was === undefined) continue
  for (const k of KEEP) if (was[k] !== undefined && was[k] !== null && was[k] !== 'NONE') s[k] = was[k]
}

const byTier = screens.reduce((a, s) => ({ ...a, [s.tier]: (a[s.tier] ?? 0) + 1 }), {})
const byStatus = screens.reduce((a, s) => ({ ...a, [s.status]: (a[s.status] ?? 0) + 1 }), {})

await mkdir(path.dirname(OUT), { recursive: true })
await writeFile(
  OUT,
  `${JSON.stringify(
    {
      $comment:
        'Generated by scripts/build-atlas-tracker.mjs from UI_ATLAS.md §9. Edit statuses here; ' +
        're-running the script preserves them. Never mark VERIFIED without a browser inspection ' +
        'AND a passing Playwright assertion — a clean tsc moves nothing.',
      source: 'MD FILES/UI_ATLAS.md §9 (lines 1800–2135)',
      statuses: ['NOT_STARTED', 'SCAFFOLDED', 'VISIBLE', 'INTERACTIVE', 'VERIFIED', 'BLOCKED'],
      totals: { screens: screens.length, byTier, byStatus },
      screens,
    },
    null,
    2,
  )}\n`,
  'utf8',
)

console.log(`atlas-tracker.json — ${screens.length} screens`)
console.log(`  tiers   ${JSON.stringify(byTier)}`)
console.log(`  status  ${JSON.stringify(byStatus)}`)
